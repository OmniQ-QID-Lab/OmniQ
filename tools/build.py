#!/usr/bin/env python3
"""Build residual_agents/orchestrator.py from fragments/.

    python tools/build.py            write residual_agents/orchestrator.py
    python tools/build.py --check    build in memory and compare with the committed file (exit 1 if they differ)

The orchestrator is one Python namespace. Its source is kept as fragments that are concatenated byte for byte in the
order of fragments/MANIFEST.txt, below a one-line header. The built file is committed; never edit it by hand.
"""
import argparse
import ast
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FRAG = os.path.join(ROOT, "fragments")
OUT = os.path.join(ROOT, "residual_agents", "orchestrator.py")
HEADER = "# Generated by tools/build.py from fragments/ in the order of fragments/MANIFEST.txt. Do not edit this file.\n"


def manifest():
    names = []
    with open(os.path.join(FRAG, "MANIFEST.txt"), encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if s and not s.startswith("#"):
                names.append(s)
    return names


def build_bytes():
    names = manifest()
    errors = []
    if len(set(names)) != len(names):
        errors.append("MANIFEST.txt lists a fragment twice")
    present = sorted(f for f in os.listdir(FRAG) if f.endswith(".py"))
    for f in present:
        if f not in names:
            errors.append("fragment not in MANIFEST.txt: %s" % f)
    parts = [HEADER.encode("utf-8")]
    for n in names:
        p = os.path.join(FRAG, n)
        if not os.path.isfile(p):
            errors.append("missing fragment: %s" % n)
            continue
        b = open(p, "rb").read()
        if not b.endswith(b"\n"):
            errors.append("fragment does not end with a newline: %s" % n)
        parts.append(b)
    if errors:
        sys.exit("build.py: " + "; ".join(errors))
    out = b"".join(parts)
    try:
        ast.parse(out.decode("utf-8"), filename="orchestrator.py")
    except SyntaxError as e:
        sys.exit("build.py: the built module does not parse: line %s: %s" % (e.lineno, e.msg))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="compare a fresh build with the committed file")
    a = ap.parse_args(argv)
    out = build_bytes()
    if a.check:
        cur = open(OUT, "rb").read() if os.path.exists(OUT) else b""
        if cur != out:
            print("build.py --check: residual_agents/orchestrator.py differs from a fresh build of fragments/ (run tools/build.py)")
            return 1
        print("build.py --check: OK (%d fragments, %d lines)" % (len(manifest()), out.count(b"\n")))
        return 0
    with open(OUT, "wb") as f:
        f.write(out)
    print("build.py: wrote residual_agents/orchestrator.py (%d fragments, %d lines)" % (len(manifest()), out.count(b"\n")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
